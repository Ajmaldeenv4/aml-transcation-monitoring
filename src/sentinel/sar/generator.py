"""Template-first Suspicious Activity Report (SAR) narrative generator.

Produces the structured draft an analyst actually writes: what triggered the
alert, what was reviewed, the typology, and the recommendation. It is fully
deterministic and offline (no LLM dependency); an LLM phrasing layer can be added
later as a clearly-flagged enhancement.
"""

from __future__ import annotations

from datetime import UTC, datetime

from sentinel.models import Alert, SARDraft

# Per-typology description of what the scenario indicates, for the narrative body.
_TYPOLOGY_NARRATIVE = {
    "structuring": (
        "multiple cash transactions sized just below the reporting threshold within a "
        "short period, consistent with structuring (smurfing) to avoid currency "
        "transaction reporting"
    ),
    "rapid_movement": (
        "funds credited to the account and almost fully moved out within a short window, "
        "consistent with the account being used as a pass-through conduit (layering)"
    ),
    "round_amount": (
        "frequent round-value transfers to the same counterparty, consistent with "
        "layering of illicit proceeds"
    ),
    "threshold_avoidance": (
        "repeated transactions sized just below a regulatory/EDD trigger, consistent with "
        "deliberate threshold avoidance"
    ),
    "high_risk_geography": (
        "value transferred to/from a jurisdiction on the firm's high-risk watchlist"
    ),
    "velocity_spike": (
        "a sudden, anomalous increase in transaction value relative to the account's own "
        "historical baseline"
    ),
    "network_ring": (
        "a cluster of accounts cycling funds among themselves, consistent with a mule "
        "network"
    ),
}


def generate_sar_narrative(
    alert: Alert,
    entity_name: str | None = None,
    reviewed_by: str = "the reviewing analyst",
) -> SARDraft:
    """Build a structured SAR narrative draft from an alert and its evidence."""
    typ = alert.rule_id.value
    subject = entity_name or alert.entity_id
    indicator = _TYPOLOGY_NARRATIVE.get(typ, "activity inconsistent with expected behaviour")

    evidence_lines = "\n".join(f"  - {k}: {v}" for k, v in alert.evidence.items())
    risk_line = (
        f"The ML risk model scored this alert {alert.risk_score:.0f}/100"
        + (f" (key factors: {', '.join(alert.risk_reasons)})." if alert.risk_reasons else ".")
        if alert.risk_score is not None
        else "This alert was generated by the rules engine (not yet ML-scored)."
    )

    narrative = f"""SUSPICIOUS ACTIVITY REPORT — DRAFT (synthetic data)

Subject: {subject}
Alert reference: {alert.alert_id}
Typology: {alert.typology_label}
Severity: {alert.severity.value}

1. What triggered this report
The {alert.typology_label} scenario was triggered for {subject}. The system observed {indicator}.

2. Transactions in scope
{len(alert.triggering_txn_ids)} transaction(s) triggered this alert: {', '.join(alert.triggering_txn_ids)}.
Supporting evidence:
{evidence_lines}

3. Risk assessment
{risk_line}

4. Recommendation
On the basis of the above, {reviewed_by} recommends this activity be escalated for
Suspicious Activity Report / Suspicious Transaction Report filing and that enhanced
due diligence be applied to the subject. This draft is generated from synthetic data
for demonstration and requires analyst review before any filing.
"""

    return SARDraft(
        alert_id=alert.alert_id,
        narrative=narrative,
        typology=alert.rule_id,
        generated_at=datetime.now(UTC),
    )
